import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { setTimeout as delay } from 'node:timers/promises';
import { configDir } from './paths.js';

/**
 * User-level service (starts at login, no admin rights):
 *   macOS   -> LaunchAgent in ~/Library/LaunchAgents, managed with launchctl
 *   Windows -> Task Scheduler task with a logon trigger for the current user
 *
 * It has to live in the user's login session either way: the 1Password SSH
 * agent and its approval prompts are not reachable from a system service.
 *
 * Backends share one shape:
 *   name, location, startsOnInstall, isInstalled(), install(spec), start(),
 *   unload() (stop supervising; may kill the service process), uninstall()
 * where spec = { node, entry, options, env, logFile, workingDirectory }; `options`
 * are the `serve` options (--config ...), `entry` the CLI script run by `node`.
 */

/** A non-default state directory gets its own service, so instances don't collide. */
export function serviceSuffix() {
  const dir = configDir();
  if (dir === path.join(os.homedir(), '.config', 'pamssh-mcp')) return '';
  return createHash('sha256').update(dir).digest('hex').slice(0, 8);
}

function run(cmd, args) {
  const r = spawnSync(cmd, args, { encoding: 'utf8', windowsHide: true });
  if (r.error) return { ok: false, output: r.error.message };
  return { ok: r.status === 0, status: r.status, output: `${r.stdout || ''}${r.stderr || ''}`.trim() };
}

function must(cmd, args) {
  const r = run(cmd, args);
  if (!r.ok) throw new Error(`${cmd} ${args.join(' ')} failed${r.output ? `: ${r.output}` : ''}`);
  return r;
}

const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// ---------- macOS: launchd ----------

export function launchdLabel() {
  const suffix = serviceSuffix();
  return `io.github.pamssh-mcp${suffix ? `.${suffix}` : ''}`;
}

export function buildLaunchdPlist({ label, node, entry, options, env, logFile, workingDirectory }) {
  const strings = (list) => list.map((s) => `    <string>${xml(s)}</string>`).join('\n');
  const envEntries = Object.entries(env)
    .map(([k, v]) => `    <key>${xml(k)}</key>\n    <string>${xml(v)}</string>`).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by \`pamssh-mcp serve install\`; remove with \`pamssh-mcp serve uninstall\`. -->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${xml(label)}</string>
  <key>ProgramArguments</key>
  <array>
${strings([node, entry, 'serve', ...options])}
  </array>
  <key>EnvironmentVariables</key>
  <dict>
${envEntries}
  </dict>
  <key>WorkingDirectory</key>
  <string>${xml(workingDirectory)}</string>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <dict>
    <key>SuccessfulExit</key>
    <false/>
  </dict>
  <key>StandardOutPath</key>
  <string>${xml(logFile)}</string>
  <key>StandardErrorPath</key>
  <string>${xml(logFile)}</string>
</dict>
</plist>
`;
}

function launchdBackend() {
  const label = launchdLabel();
  const domain = `gui/${process.getuid()}`;
  const target = `${domain}/${label}`;
  const plist = path.join(os.homedir(), 'Library', 'LaunchAgents', `${label}.plist`);
  const isLoaded = () => run('launchctl', ['print', target]).ok;

  async function bootstrap() {
    run('launchctl', ['enable', target]); // in case it was disabled earlier (`launchctl unload -w`)
    let r;
    for (let i = 0; i < 10; i++) {
      r = run('launchctl', ['bootstrap', domain, plist]);
      if (r.ok || isLoaded()) return;
      await delay(500); // the previous instance may still be on its way out
    }
    throw new Error(`launchctl bootstrap ${domain} ${plist} failed: ${r.output}\n`
      + 'A LaunchAgent needs your graphical login session (it cannot be loaded from a plain SSH login).');
  }

  async function unload() {
    if (!isLoaded()) return;
    run('launchctl', ['bootout', target]); // SIGTERM, then SIGKILL after launchd's exit timeout
    for (let i = 0; i < 60 && isLoaded(); i++) await delay(500);
    if (isLoaded()) throw new Error(`launchctl bootout ${target} did not finish`);
  }

  return {
    name: 'launchd',
    id: label,
    location: plist,
    startsOnInstall: true, // RunAtLoad
    isInstalled: () => fs.existsSync(plist),
    isLoaded,
    async install(spec) {
      await unload();
      fs.mkdirSync(path.dirname(plist), { recursive: true });
      fs.mkdirSync(path.dirname(spec.logFile), { recursive: true });
      // KeepAlive.SuccessfulExit=false: restart after a crash, stay down after a clean
      // stop. PAMSSH_MCP_SERVICE makes a duplicate start exit 0 so launchd doesn't loop.
      const env = { PATH: launchdPath(spec.node), HOME: os.homedir(), ...spec.env, PAMSSH_MCP_SERVICE: 'launchd' };
      fs.writeFileSync(plist, buildLaunchdPlist({ ...spec, label, env }), { mode: 0o644 });
      await bootstrap();
    },
    async start() {
      if (isLoaded()) must('launchctl', ['kickstart', target]);
      else await bootstrap();
    },
    unload,
    async uninstall() {
      await unload();
      fs.rmSync(plist, { force: true });
    },
  };
}

function launchdPath(node) {
  const dirs = [path.dirname(node), '/opt/homebrew/bin', '/usr/local/bin', '/usr/bin', '/bin', '/usr/sbin', '/sbin'];
  return [...new Set(dirs)].join(':');
}

// ---------- Windows: Task Scheduler ----------

export function windowsTaskName() {
  const suffix = serviceSuffix();
  return `pamssh-mcp${suffix ? `-${suffix}` : ''}`;
}

/** Quote one argument the way the Windows C runtime parses a command line. */
export function winQuote(arg) {
  if (arg !== '' && !/[\s"]/.test(arg)) return arg;
  return `"${arg.replace(/(\\*)"/g, '$1$1\\"').replace(/(\\+)$/, '$1$1')}"`;
}

/**
 * The task only launches `serve start`, which detaches the real server and
 * exits: a console program kept running by Task Scheduler in an interactive
 * session would leave a console window open. --no-service makes that start
 * spawn the server itself instead of running this task again.
 */
export function buildTaskXml({ userId, node, entry, options, workingDirectory }) {
  const argLine = [entry, 'serve', 'start', '--no-service', ...options].map(winQuote).join(' ');
  return `<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>pamssh-mcp MCP server: start at logon (pamssh-mcp serve install)</Description>
  </RegistrationInfo>
  <Triggers>
    <LogonTrigger>
      <Enabled>true</Enabled>
      <UserId>${xml(userId)}</UserId>
    </LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>${xml(userId)}</UserId>
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <WakeToRun>false</WakeToRun>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>7</Priority>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>${xml(node)}</Command>
      <Arguments>${xml(argLine)}</Arguments>
      <WorkingDirectory>${xml(workingDirectory)}</WorkingDirectory>
    </Exec>
  </Actions>
</Task>
`;
}

/** SID of the current user (works for local, domain and Microsoft accounts alike). */
function windowsUserId() {
  const r = run('whoami', ['/user', '/fo', 'csv', '/nh']);
  const sid = r.ok && /"(S-1-[0-9-]+)"/.exec(r.output);
  if (sid) return sid[1];
  const user = os.userInfo().username;
  return process.env.USERDOMAIN ? `${process.env.USERDOMAIN}\\${user}` : user;
}

function windowsBackend() {
  const name = windowsTaskName();
  return {
    name: 'Task Scheduler',
    id: name,
    location: `Task Scheduler task "${name}"`,
    startsOnInstall: false,
    isInstalled: () => run('schtasks', ['/Query', '/TN', name]).ok,
    async install(spec) {
      fs.mkdirSync(path.dirname(spec.logFile), { recursive: true });
      // A logon trigger scoped to the current user is what a non-admin may register;
      // `schtasks /SC ONLOGON` (any user) needs elevation. schtasks wants UTF-16 XML.
      const file = path.join(os.tmpdir(), `pamssh-mcp-task-${process.pid}.xml`);
      fs.writeFileSync(file, `﻿${buildTaskXml({ ...spec, userId: windowsUserId() })}`, 'utf16le');
      try {
        must('schtasks', ['/Create', '/TN', name, '/XML', file, '/F']);
      } finally {
        fs.rmSync(file, { force: true });
      }
    },
    async start() { must('schtasks', ['/Run', '/TN', name]); },
    async unload() { /* the task only launches the server; nothing supervises it */ },
    async uninstall() { must('schtasks', ['/Delete', '/TN', name, '/F']); },
  };
}

/** Service backend for this platform, or null where none is implemented. */
export function serviceBackend(platform = process.platform) {
  if (platform === 'darwin') return launchdBackend();
  if (platform === 'win32') return windowsBackend();
  return null;
}
